// Generates src/app-theme-colors.css: inside ".theme-app" every blue and indigo Tailwind
// color becomes teal (Option 2 look). Merchant and franchise screens are not under ".theme-app",
// so they are untouched. Run: node scripts/gen-app-theme-colors.mjs
import { writeFileSync } from 'node:fs';

const teal = { 50:'#f0fdfa',100:'#ccfbf1',200:'#99f6e4',300:'#5eead4',400:'#2dd4bf',500:'#14b8a6',600:'#0d9488',700:'#0f766e',800:'#115e59',900:'#134e4a' };
// blue/indigo shade -> teal shade (primary 600 becomes 700 = #0f766e, the Option 2 teal)
const shift = { 50:50,100:100,200:200,300:300,400:500,500:600,600:700,700:800,800:900,900:900 };
const rgb = (hex) => { const n = parseInt(hex.slice(1), 16); return `${n >> 16} ${(n >> 8) & 255} ${n & 255}`; };

const hues = ['blue', 'indigo'];
const shades = Object.keys(shift);
const states = ['', 'hover', 'focus', 'active'];
let css = '/* GENERATED by scripts/gen-app-theme-colors.mjs - do not edit by hand. */\n';

const decl = (prop, c) => {
  const v = rgb(teal[shift[c]]);
  switch (prop) {
    case 'bg': return `--tw-bg-opacity:1;background-color:rgb(${v}/var(--tw-bg-opacity))`;
    case 'text': return `--tw-text-opacity:1;color:rgb(${v}/var(--tw-text-opacity))`;
    case 'border': return `--tw-border-opacity:1;border-color:rgb(${v}/var(--tw-border-opacity))`;
    case 'ring': return `--tw-ring-opacity:1;--tw-ring-color:rgb(${v}/var(--tw-ring-opacity))`;
    case 'from': return `--tw-gradient-from:rgb(${v}) var(--tw-gradient-from-position);--tw-gradient-to:rgb(${v}/0) var(--tw-gradient-to-position);--tw-gradient-stops:var(--tw-gradient-from),var(--tw-gradient-to)`;
    case 'via': return `--tw-gradient-to:rgb(${v}/0) var(--tw-gradient-to-position);--tw-gradient-stops:var(--tw-gradient-from),rgb(${v}) var(--tw-gradient-via-position),var(--tw-gradient-to)`;
    case 'to': return `--tw-gradient-to:rgb(${v}) var(--tw-gradient-to-position)`;
  }
};

for (const hue of hues) for (const c of shades) for (const prop of ['bg', 'text', 'border', 'ring', 'from', 'via', 'to']) {
  for (const st of states) {
    if (st && ['from', 'via', 'to'].includes(prop)) continue;
    const cls = `${st ? st + '\\:' : ''}${prop}-${hue}-${c}`;
    const pseudo = st ? `:${st}` : '';
    css += `.theme-app .${cls}${pseudo}{${decl(prop, c)}}\n`;
  }
  // group-hover for bg/text
  for (const prop of ['bg', 'text']) {
    css += `.theme-app .group:hover .group-hover\\:${prop}-${hue}-${c}{${decl(prop, c)}}\n`;
  }
}
writeFileSync(new URL('../src/app-theme-colors.css', import.meta.url), css);
console.log('rules:', css.split('\n').length - 2);
